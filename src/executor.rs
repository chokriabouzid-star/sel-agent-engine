/// تنظيف الكود من Unicode quotes
fn sanitize_code(s: &str) -> String {
    let original_len = s.len();
    let result = s
        .replace(['\u{201C}', '\u{201D}'], "\"")
        .replace(['\u{2018}', '\u{2019}'], "'")
        .replace('\u{2014}', "--")
        .replace('\u{2013}', "-")
        .replace('\u{00A0}', " ")
        .replace(['\u{200B}', '\u{FEFF}'], "")
        .replace("\r\n", "\n")
        .to_string();

    if result.len() != original_len {
        eprintln!(
            "[TRACE] sanitize_code: cleaned {} Unicode chars",
            original_len - result.len()
        );
    }
    result
}

fn fix_toml_duplicates(src: &str) -> String {
    // v7.5: Basic fix for duplicate keys in [package] section of Cargo.toml
    let lines: Vec<String> = src.lines().map(|s| s.to_string()).collect();
    let mut seen_keys = std::collections::HashSet::new();
    let mut result = Vec::new();

    // We process from bottom to top to keep the LATEST assignment (likely the one the model just added)
    for line in lines.iter().rev() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('[') || trimmed.starts_with('#') {
            result.push(line.clone());
            if trimmed.starts_with('[') {
                seen_keys.clear();
            } // Reset on new section
            continue;
        }

        if let Some(pos) = trimmed.find('=') {
            let key = trimmed[..pos].trim();
            if seen_keys.contains(key) {
                eprintln!(
                    "[TRACE] fix_toml_duplicates: removed duplicate key '{}'",
                    key
                );
                continue;
            }
            seen_keys.insert(key.to_string());
        }
        result.push(line.clone());
    }
    result.reverse();
    result.join("\n")
}

fn fix_go_backslashes(src: &str) -> String {
    // v7.5: Fix for illegal backslash escapes in Go strings (common hallucination)
    src.replace("\\\\n", "\\n")
        .replace("\\\\t", "\\t")
        .replace("\\\\\"", "\\\"")
}

