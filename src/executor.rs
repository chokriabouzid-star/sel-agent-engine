fn fix_rust_string_types(content: &str) -> String {
    let ends_with_newline = content.ends_with('\n');
    let lines: Vec<String> = content
        .lines()
        .map(|line| {
            let line = fix_rust_pattern(line, "Err(\"", "Err(\"", "\".to_string())");
            let line = fix_rust_pattern(&line, ".ok_or(\"", ".ok_or(\"", "\".to_string())");
            let line = fix_rust_pattern(
                &line,
                ".ok_or_else(|| \"",
                ".ok_or_else(|| \"",
                "\".to_string())",
            );
            line
        })
        .collect();
    let mut out = lines.join("\n");
    if ends_with_newline && !out.ends_with('\n') {
        out.push('\n');
    }
    out
}

/// يبحث عن open + "msg" + ) ويستبدلها بـ open + "msg" + new_close
/// يتجاهل السطر إذا كان يحتوي .to_string() بعد الـ msg مباشرة
fn fix_rust_pattern(line: &str, open: &str, new_open: &str, new_close: &str) -> String {
    if !line.contains(open) {
        return line.to_string();
    }
    let mut result = String::new();
    let mut rest = line;
    while let Some(pos) = rest.find(open) {
        result.push_str(&rest[..pos]);
        let after = &rest[pos + open.len()..];
        // ابحث عن إغلاق الـ string: "
        if let Some(q) = after.find('"') {
            let msg = &after[..q];
            let tail = &after[q + 1..]; // بعد الـ "
            if tail.starts_with(".to_string()") {
                // مُحوَّل مسبقاً — اكتبه كما هو
                result.push_str(new_open);
                result.push_str(msg);
                result.push('"');
                rest = tail; // يبدأ بـ .to_string()...
            } else {
                // تحويل: أضف .to_string() وتجاوز ) النهائية
                result.push_str(new_open);
                result.push_str(msg);
                result.push_str(new_close);
                // تجاوز ) القديمة
                rest = if tail.starts_with(')') {
                    &tail[1..]
                } else {
                    tail
                };
            }
        } else {
            // لا يوجد إغلاق — اكتب كما هو
            result.push_str(open);
            rest = after;
        }
    }
    result.push_str(rest);
    result
}

