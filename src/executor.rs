/// v7.9.6: Python syntax check — catches SyntaxError/IndentationError without LLM
/// Uses py_compile (stdlib) — works fully offline
fn python_syntax_check(file: &std::path::Path) -> Option<String> {
    if !file.exists() || !file.extension().map(|e| e == "py").unwrap_or(false) {
        return None;
    }
    let file_str = file.to_string_lossy();
    eprintln!("[TRACE] python_syntax_check: checking {}", file_str);
    
    // Use python3 -m py_compile which is stdlib (no pip needed)
    let out = std::process::Command::new("python3")
        .args(["-m", "py_compile", &file_str])
        .output()
        .ok()?;
    
    if !out.status.success() {
        let stderr = String::from_utf8_lossy(&out.stderr).to_string();
        // Filter to show only the relevant error lines
        let error_msg: String = stderr
            .lines()
            .filter(|l| {
                l.contains("SyntaxError")
                    || l.contains("IndentationError")
                    || l.contains("TabError")
                    || l.contains("File \"")
                    || l.trim().starts_with('^')
                    || l.contains("line ")
            })
            .collect::<Vec<_>>()
            .join("\n");
        if error_msg.is_empty() {
            Some(stderr)
        } else {
            Some(error_msg)
        }
    } else {
        None
    }
}

/// v7.9.9 P6: Semantic Guard for tests
fn guard_assertion_integrity(path: &str, before: &str, after: &str) -> std::result::Result<(), String> {
    let before_asserts = count_assertions(before);
    let after_asserts = count_assertions(after);
    
    if after_asserts < before_asserts {
        return Err(format!(
            "BLOCKED: ASSERTION GUARD: patch on '{}' would reduce assertion count from {} to {} — this weakens test quality. Fix the SOURCE code instead.",
            path, before_asserts, after_asserts
        ));
    }
    
    let before_vals = extract_expected_values(before);
    let after_vals = extract_expected_values(after);
    if !before_vals.is_subset(&after_vals) {
        return Err(format!(
            "BLOCKED: ASSERTION GUARD: patch on '{}' would change expected values (e.g. literals in assertions). This is FORBIDDEN. Fix the SOURCE code to match existing tests.",
            path
        ));
    }
    
    Ok(())
}

/// v7.9.9 P6: Count assertion statements in test file
/// Used by Semantic Guard to prevent test weakening
fn count_assertions(content: &str) -> usize {
    content.lines().filter(|l| {
        let t = l.trim();
        // Python
        t.starts_with("assert ") || t.contains("assertEqual") || t.contains("assertRaises")
        // Go
        || t.contains("t.Errorf") || t.contains("t.Fatal") || t.contains("t.Error(")
        // JS/TS
        || t.contains("expect(") || t.contains("assert.") || t.contains("toBe(")
        // Rust
        || t.contains("assert_eq!") || t.contains("assert_ne!") || t.contains("assert!(")
    }).count()
}

/// v7.9.9 P6: Extract expected values from assertion strings
/// Regex-based heuristic to detect literal changes in tests
fn extract_expected_values(content: &str) -> std::collections::BTreeSet<String> {
    let mut values = std::collections::BTreeSet::new();
    // Extract all numbers and quoted strings as a heuristic for test literals
    let re = regex::Regex::new(r#""[^"]*"|'[^']*'|-?\b\d+\b"#).unwrap();
    for cap in re.captures_iter(content) {
        values.insert(cap[0].to_string());
    }
    values
}

/// AutoFix: يضيف Go stdlib import تلقائياً بدون LLM
fn autofix_go_undefined_import(file: &std::path::Path, err: &str) -> Option<String> {
    let filename = file.file_name()?.to_str()?;
    let go_std: &[(&str, &str)] = &[
        ("fmt", "fmt"),
        ("errors", "errors"),
        ("strings", "strings"),
        ("strconv", "strconv"),
        ("sort", "sort"),
        ("math", "math"),
        ("os", "os"),
        ("io", "io"),
        ("log", "log"),
        ("time", "time"),
        ("sync", "sync"),
        ("context", "context"),
        ("bytes", "bytes"),
        ("bufio", "bufio"),
    ];

    // استخرج الرمز من "undefined: fmt"
    let sym = err
        .lines()
        .find(|l| l.contains(filename) && l.contains("undefined:"))?
        .split("undefined:")
        .nth(1)?
        .split_whitespace()
        .next()?
        .split('.')
        .next()?
        .to_string();

    // تحقق أنه stdlib
    let pkg = go_std
        .iter()
        .find(|(name, _)| *name == sym.as_str())
        .map(|(_, pkg)| *pkg)?;

    // اقرأ الملف
    let src = std::fs::read_to_string(file).ok()?;

    // إذا كان موجوداً بالفعل
    if src.contains(&format!("\"{}\"", pkg)) {
        return None;
    }

    // أضف import
    let new_src = if src.contains("import (") {
        src.replacen("import (", &format!("import (\n\t\"{}\"", pkg), 1)
    } else {
        // أضف بعد package declaration
        let pkg_line = src.lines().find(|l| l.starts_with("package "))?.to_string();
        src.replacen(&pkg_line, &format!("{}\n\nimport \"{}\"", pkg_line, pkg), 1)
    };

    std::fs::write(file, &new_src).ok()?;
    Some(pkg.to_string())
}

/// AutoFix: يحذف Go import غير مستخدم
fn autofix_go_unused_import(file: &std::path::Path, err: &str) -> Option<String> {
    let filename = file.file_name()?.to_str()?;
    let pkg = err
        .lines()
        .find(|l| l.contains(filename) && l.contains("imported and not used"))?
        .split('"')
        .nth(1)?
        .to_string();

    if pkg.is_empty() {
        return None;
    }

    let src = std::fs::read_to_string(file).ok()?;

    let block_pattern = format!("\t\"{}\"", pkg);
    let block_pattern_no_tab = format!("    \"{}\"", pkg);

    let new_src = if src.contains(&block_pattern) {
        let lines: Vec<&str> = src.lines().collect();
        let filtered: Vec<&str> = lines
            .iter()
            .filter(|&&line| {
                let trimmed = line.trim();
                trimmed != format!("\"{}\"", pkg).as_str()
            })
            .cloned()
            .collect();
        let new = filtered.join("\n");
        new.replace("import (\n)", "").replace("import (\n\n)", "")
    } else if src.contains(&block_pattern_no_tab) {
        src.lines()
            .filter(|line| line.trim() != format!("\"{}\"", pkg).as_str())
            .collect::<Vec<_>>()
            .join("\n")
    } else {
        let single_pattern = format!("import \"{}\"", pkg);
        if src.contains(&single_pattern) {
            src.lines()
                .filter(|line| !line.trim().starts_with(&single_pattern))
                .collect::<Vec<_>>()
                .join("\n")
        } else {
            return None;
        }
    };

    let new_src = {
        let mut cleaned = new_src.clone();
        while let Some(start) = cleaned.find("import (") {
            if let Some(end) = cleaned[start..].find(')') {
                let block_content = &cleaned[start + 8..start + end];
                if block_content.trim().is_empty() {
                    cleaned = format!("{}{}", &cleaned[..start], &cleaned[start + end + 1..]);
                } else {
                    break;
                }
            } else {
                break;
            }
        }
        cleaned
    };

    std::fs::write(file, &new_src).ok()?;
    Some(pkg)
}

fn find_cargo_workspace(root: &std::path::Path) -> std::path::PathBuf {
    if root.join("Cargo.toml").exists() {
        return root.to_path_buf();
    }
    if let Ok(entries) = std::fs::read_dir(root) {
        for entry in entries.flatten() {
            let sub = entry.path();
            if sub.is_dir() && sub.join("Cargo.toml").exists() {
                return sub;
            }
        }
    }
    root.to_path_buf()
}

/// v8.0 — Fix Llama writing `-go 1.21` instead of `go 1.21` in go.mod files
fn sanitize_go_mod_content(content: &str) -> String {
    let fixed: Vec<String> = content
        .lines()
        .map(|line| {
            let trimmed = line.trim_start();
            if trimmed.starts_with("-go ") {
                let leading = &line[..line.len() - trimmed.len()];
                format!("{}{}", leading, trimmed.replacen("-go ", "go ", 1))
            } else if trimmed.starts_with("go=") {
                let leading = &line[..line.len() - trimmed.len()];
                format!("{}{}", leading, trimmed.replacen("go=", "go ", 1))
            } else {
                line.to_string()
            }
        })
        .collect();
    let result = fixed.join("\n");
    if result != content {
        eprintln!("   🔧 AutoFix: corrected go.mod directive syntax (-go → go)");
    }
    result
}

