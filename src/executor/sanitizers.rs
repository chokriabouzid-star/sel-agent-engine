/// Fix Go files missing package declaration at top
/// يحدث عندما يُنتج LLM Go code بدون "package main" أو "package foo"
pub fn fix_go_missing_package(content: &str, default_pkg: &str) -> String {
    let first_non_empty = content.lines().find(|l| !l.trim().is_empty());
    match first_non_empty {
        Some(line) if line.trim().starts_with("package ") => content.to_string(),
        _ => format!("package {}\n\n{}", default_pkg, content),
    }
}

pub fn fix_rust_string_literals(src: &str) -> String {
    let mut result = String::with_capacity(src.len());
    let bytes = src.as_bytes();
    let mut i = 0;

    while i < bytes.len() {
        if bytes[i] == b'\'' {
            let start = i + 1;
            let mut end = start;
            let mut blocked = false;

            while end < bytes.len() && bytes[end] != b'\'' && bytes[end] != b'\n' {
                if matches!(
                    bytes[end],
                    b' ' | b'\t'
                        | b'('
                        | b')'
                        | b'['
                        | b']'
                        | b'{'
                        | b'}'
                        | b'<'
                        | b'>'
                        | b','
                        | b';'
                        | b':'
                        | b'&'
                ) {
                    blocked = true;
                    break;
                }
                end += 1;
            }

            if !blocked && end < bytes.len() && bytes[end] == b'\'' && end > start {
                let word = &src[start..end];
                let word_len = word.chars().count();

                let is_escape = word.contains('\\');
                let is_char_digit = word_len == 1
                    && word
                        .chars()
                        .next()
                        .map(|c| c.is_ascii_digit())
                        .unwrap_or(false);
                let is_char_single = word_len == 1;

                let should_convert =
                    word_len > 1 && !is_escape && !is_char_digit && !is_char_single;

                if should_convert {
                    result.push('"');
                    result.push_str(word);
                    result.push('"');
                    i = end + 1;
                    continue;
                }
            }
        }

        let Some(ch) = src[i..].chars().next() else {
            break;
        };
        result.push(ch);
        i += ch.len_utf8();
    }

    result
}

/// Sanitize broken Rust lifetime quotes generated by weak LLMs (e.g. Groq).
/// Fixes patterns like `"static str`  `&'static str` and Unicode lifetime markers.
pub fn sanitize_rust_lifetime_quotes(content: &str) -> String {
    content
        // Fix "static  &'static (common Groq hallucination)
        .replace("\"static str", "&'static str")
        .replace("\u{201C}static", "&'static")
        .replace("\u{2018}static", "'static")
        // Fix broken return type arrows
        .replace("-> \"static", "-> &'static")
        .replace("-> \u{201C}static", "-> &'static")
        // Fix missing & before 'static
        .replace("-> 'static str", "-> &'static str")
}

pub fn fix_rust_test_attributes(src: &str) -> String {
    let had_trailing_newline = src.ends_with('\n');
    let mut fixed_lines = Vec::new();

    for line in src.lines() {
        let trimmed = line.trim_start();
        let indent = &line[..line.len() - trimmed.len()];

        if trimmed == "[cfg(test)]" {
            fixed_lines.push(format!("{}#[cfg(test)]", indent));
        } else if trimmed == "[test]" {
            fixed_lines.push(format!("{}#[test]", indent));
        } else {
            fixed_lines.push(line.to_string());
        }
    }

    let mut out = fixed_lines.join("\n");
    if had_trailing_newline {
        out.push('\n');
    }
    out
}

/// v8.0  Fix Llama writing `-go 1.21` instead of `go 1.21` in go.mod files
#[allow(dead_code)] // v9.x: Go module sanitizer — reserved for go.mod repair path
pub fn sanitize_go_mod_content(content: &str) -> String {
    let fixed: Vec<String> = content
        .lines()
        .map(|line| {
            let trimmed = line.trim_start();
            if trimmed.starts_with("-go ") {
                let leading = &line[..line.len() - trimmed.len()];
                format!("{}{}", leading, trimmed.replacen("-go ", "go ", 1))
            } else if trimmed.starts_with("go=") {
                let leading = &line[..line.len() - trimmed.len()];
                format!("{}{}", leading, trimmed.replacen("go=", "go ", 1))
            } else {
                line.to_string()
            }
        })
        .collect();
    let result = fixed.join("\n");
    if result != content {
        eprintln!("    AutoFix: corrected go.mod directive syntax (-go  go)");
    }
    result
}

