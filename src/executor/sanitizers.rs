///    Unicode quotes
pub fn sanitize_code(s: &str) -> String {
    let original_len = s.len();
    let result = s
        .replace(['\u{201C}', '\u{201D}'], "\"")
        .replace(['\u{2018}', '\u{2019}'], "'")
        .replace('\u{2014}', "--")
        .replace('\u{2013}', "-")
        .replace('\u{00A0}', " ")
        .replace(['\u{200B}', '\u{FEFF}'], "")
        .replace("\r\n", "\n")
        .to_string();

    if result.len() != original_len {
        eprintln!(
            "[TRACE] sanitize_code: cleaned {} Unicode chars",
            original_len - result.len()
        );
    }
    result
}

/// Fix Python assert strings where a weak LLM used single quotes outside
/// a payload that already contains tuple/string syntax.
fn normalize_problematic_python_assert(line: &str) -> Option<String> {
    let assert_pos = line.find("assert '")?;
    let quote_start = assert_pos + "assert ".len();
    let after_open = &line[quote_start + 1..];
    let relative_end = after_open.find("' in ")?;
    let quote_end = quote_start + 1 + relative_end;
    let inner = &line[quote_start + 1..quote_end];

    let looks_problematic = inner.contains("('")
        || inner.contains("',")
        || inner.contains("')")
        || inner.contains("[(")
        || inner.contains(")]")
        || inner.contains('"');

    if !looks_problematic {
        return None;
    }

    let normalized_inner = inner.replace('"', "'");
    Some(format!(
        "{}\"{}\"{}",
        &line[..quote_start],
        normalized_inner,
        &line[quote_end + 1..]
    ))
}

pub fn fix_python_string_quoting(src: &str) -> String {
    let had_trailing_newline = src.ends_with('\n');
    let mut fixed_lines = Vec::new();

    for line in src.lines() {
        if let Some(fixed) = normalize_problematic_python_assert(line) {
            fixed_lines.push(fixed);
        } else {
            fixed_lines.push(line.to_string());
        }
    }

    let mut out = fixed_lines.join("\n");
    if had_trailing_newline {
        out.push('\n');
    }
    out
}

#[allow(dead_code)] // documented in SEL_AGENT_REFERENCE_v9.3.2 — Cargo.toml duplicate key fix
pub fn fix_toml_duplicates(src: &str) -> String {
    // v7.5: Basic fix for duplicate keys in [package] section of Cargo.toml
    let lines: Vec<String> = src.lines().map(|s| s.to_string()).collect();
    let mut seen_keys = std::collections::HashSet::new();
    let mut result = Vec::new();

    // We process from bottom to top to keep the LATEST assignment (likely the one the model just added)
    for line in lines.iter().rev() {
        let trimmed = line.trim();
        if trimmed.is_empty() || trimmed.starts_with('[') || trimmed.starts_with('#') {
            result.push(line.clone());
            if trimmed.starts_with('[') {
                seen_keys.clear();
            } // Reset on new section
            continue;
        }

        if let Some(pos) = trimmed.find('=') {
            let key = trimmed[..pos].trim();
            if seen_keys.contains(key) {
                eprintln!(
                    "[TRACE] fix_toml_duplicates: removed duplicate key '{}'",
                    key
                );
                continue;
            }
            seen_keys.insert(key.to_string());
        }
        result.push(line.clone());
    }
    result.reverse();
    result.join("\n")
}

pub fn fix_go_backslashes(src: &str) -> String {
    // v7.5: Fix for illegal backslash escapes in Go strings (common hallucination)
    src.replace("\\\\n", "\\n")
        .replace("\\\\t", "\\t")
        .replace("\\\\\"", "\\\"")
}

pub fn fix_rust_string_types(content: &str) -> String {
    let ends_with_newline = content.ends_with('\n');
    let lines: Vec<String> = content
        .lines()
        .map(|line| {
            let line = fix_rust_pattern(line, "Err(\"", "Err(\"", "\".to_string())");
            let line = fix_rust_pattern(&line, ".ok_or(\"", ".ok_or(\"", "\".to_string())");

            fix_rust_pattern(
                &line,
                ".ok_or_else(|| \"",
                ".ok_or_else(|| \"",
                "\".to_string())",
            )
        })
        .collect();
    let mut out = lines.join("\n");
    if ends_with_newline && !out.ends_with('\n') {
        out.push('\n');
    }
    out
}

///   open + "msg" + )   open + "msg" + new_close
///      .to_string()   msg
pub fn fix_rust_pattern(line: &str, open: &str, new_open: &str, new_close: &str) -> String {
    if !line.contains(open) {
        return line.to_string();
    }
    let mut result = String::new();
    let mut rest = line;
    while let Some(pos) = rest.find(open) {
        result.push_str(&rest[..pos]);
        let after = &rest[pos + open.len()..];
        //     string: "
        if let Some(q) = after.find('"') {
            let msg = &after[..q];
            let tail = &after[q + 1..]; //   "
            if tail.starts_with(".to_string()") {
                //
                result.push_str(new_open);
                result.push_str(msg);
                result.push('"');
                rest = tail; //   .to_string()...
            } else {
                // :  .to_string()  )
                result.push_str(new_open);
                result.push_str(msg);
                result.push_str(new_close);
                //  )
                rest = if let Some(stripped) = tail.strip_prefix(')') {
                    stripped
                } else {
                    tail
                };
            }
        } else {
            //
            result.push_str(open);
            rest = after;
        }
    }
    result.push_str(rest);
    result
}

